#define NROWS ((int)(sizeof(TABLE) / sizeof(TABLE[0])))

int main(void)
{
  dae_test T;
  int r, kmax = 0;
  double *buf;
  dae_test_begin(&T, "aceitacao 0: Bessel J_k contra tabela Wolfram/mpmath");

  for (r = 0; r < NROWS; ++r) if (TABLE[r].k > kmax) kmax = TABLE[r].k;
  buf = (double *)malloc((size_t)(kmax + 1) * sizeof(double));
  dae_test_ok(&T, buf != NULL, "alocacao");
  if (!buf) return dae_test_end(&T);

  for (r = 0; r < NROWS; ++r) {
    const double ref = TABLE[r].j;
    double got;
    dae_status st = dae_bessel_j_array(TABLE[r].x, kmax, buf);
    dae_test_ok(&T, st == DAE_OK, "J_k(%g): %s", TABLE[r].x, dae_strerror(st));
    if (st != DAE_OK) continue;
    got = buf[TABLE[r].k];
    if (fabs(ref) >= 1e-290) {
      const double rel = fabs(got - ref) / fabs(ref);
      dae_test_ok(&T, rel < 1e-12,
                  "J_%d(%g): rel=%.3g obtido=%.17g esperado=%.17g",
                  TABLE[r].k, TABLE[r].x, rel, got, ref);
    } else {
      /* Abaixo da faixa do double a única resposta certa é zero, e o que
         importa é que não saia lixo. */
      dae_test_ok(&T, fabs(got) < 1e-280,
                  "J_%d(%g) deveria zerar por underflow, veio %.3g",
                  TABLE[r].k, TABLE[r].x, got);
    }
  }

  /* Recorrência: J_{k-1}(x) + J_{k+1}(x) = (2k/x) J_k(x). Independente da
     tabela, pega erro sistemático de escala. */
  {
    const double x = 12.5;
    int k;
    dae_bessel_j_array(x, 40, buf);
    for (k = 1; k < 40; ++k) {
      const double lhs = buf[k - 1] + buf[k + 1];
      const double rhs = (2.0 * (double)k / x) * buf[k];
      dae_test_near(&T, lhs, rhs, 1e-13, "recorrencia em k=%d: ", k);
    }
    dae_test_near(&T, dae_bessel_j_array(0.0, 40, buf) == DAE_OK ? buf[0] : -1.0,
                  1.0, 0.0, "J_0(0) = 1 exato: ");
  }

  free(buf);
  return dae_test_end(&T);
}
